/**
 * Copy of a Workspace in `cacheRoot/workspace-<name>` (rebuilt on every call, without `.diagrams/`) with a
 * `screenshots.dg` that repeats the View once per Theme: `view <view>--<theme>`, without `link`.
 * Errors: it throws if the View is not in any `.dg` of the Workspace.
 */
import { cpSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { basename, join, relative } from 'node:path';

import { OUTPUT_FOLDER } from 'cli';

export interface PreparedWorkspace {
  folder: string;
  viewOf: (theme: string) => string;
}

const dgFiles = (root: string): string[] =>
  readdirSync(root, { recursive: true, withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith('.dg') && !relative(root, e.parentPath).split('/').includes(OUTPUT_FOLDER))
    .map((e) => join(e.parentPath, e.name));

/** Without the braces; skips strings and comments; `undefined` if it is not there. */
export function viewBody(text: string, id: string): string | undefined {
  const start = new RegExp(`(^|\\s)view\\s+${id.replace(/[-.]/g, '\\$&')}\\s*\\{`).exec(text);
  if (start === null) return undefined;
  const open = start.index + start[0].length;
  let depth = 1;
  for (let i = open; i < text.length; i++) {
    const c = text[i];
    if (c === '"') {
      i = text.indexOf('"', i + 1);
      if (i < 0) return undefined;
    } else if (c === '/' && text[i + 1] === '/') {
      i = text.indexOf('\n', i);
      if (i < 0) return undefined;
    } else if (c === '{') depth++;
    else if (c === '}' && --depth === 0) return text.slice(open, i);
  }
  return undefined;
}

/** Replaces (or adds) `theme`, keeps its `{ ... }` patch and removes the `link`s. */
export function withTheme(body: string, theme: string): string {
  const withoutLinks = body.replace(/(^|\s)link\s+[\w.-]+\s*->\s*[\w-]+/g, '$1');
  const changed = withoutLinks.replace(/(^|\s)theme\s+[\w-]+/, `$1theme ${theme}`);
  return changed === withoutLinks ? `\n  theme ${theme}${withoutLinks}` : changed;
}

export function prepareWorkspace(source: string, view: string, themes: readonly string[], cacheRoot: string): PreparedWorkspace {
  const folder = join(cacheRoot, `workspace-${basename(source)}`);
  rmSync(folder, { recursive: true, force: true });
  cpSync(source, folder, { recursive: true, filter: (path) => basename(path) !== OUTPUT_FOLDER });
  const body = dgFiles(folder)
    .map((file) => viewBody(readFileSync(file, 'utf8'), view))
    .find((b) => b !== undefined);
  if (body === undefined) throw new Error(`The View '${view}' is not in any .dg of ${source}.`);
  const viewOf = (theme: string): string => `${view}--${theme}`;
  const views = themes.map((t) => `view ${viewOf(t)} {${withTheme(body, t)}}\n`).join('\n');
  writeFileSync(join(folder, 'screenshots.dg'), `// Generated by \`pnpm screenshots --workspace\`: the View '${view}' with each Theme.\n${views}`);
  return { folder, viewOf };
}
