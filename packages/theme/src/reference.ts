/** Catalog reference in Markdown (English), generated from the same tables that validate. */
import { EASINGS, EFFECTS, MOTIONS, ANIMATABLE_PROPERTIES } from './animation';
import { SEQUENCE_BLOCKS, SEQUENCE_SPEC } from './sequence';
import { ROW_HEIGHT, ROW_KEYS, ROW_TEXT_NAMES, ROW_TEXTS } from './row';
import { STATES } from './patches';
import type { State } from './patches';
import { CATALOG, SLOT_DEFINITION, OFFSET_PROPERTIES, ZONE_PROPERTY, SLOTS, placementsOf } from './catalog';
import type { PrimitiveDefinition, PropertyDefinition, PrimitiveName } from './catalog';

const property = (name: string, definition: PropertyDefinition): string => {
  switch (definition.tipo) {
    case 'numero':
      return `\`${name}\` ${definition.min} to ${definition.max}${definition.defecto !== undefined ? ` (${definition.defecto})` : definition.opcional === true ? ' (optional)' : ''}`;
    case 'color':
      return `\`${name}\` Palette color${definition.opcional === true ? ' (optional)' : ''}`;
    case 'opcion':
      return `\`${name}\` ${definition.valores.join('|')}${definition.defecto !== undefined ? ` (${definition.defecto})` : definition.opcional === true ? ' (optional)' : ''}`;
    case 'nombre':
      return `\`${name}\` Component name`;
    case 'texto':
      return `\`${name}\` text up to ${definition.largo} characters${definition.opcional === true ? ' (optional)' : ''}`;
  }
};

/** Who sets each state; the table forces describing any new state. */
const STATE_ORIGIN: Readonly<Record<State, string>> = {
  planned: 'The Model: Planned elements. Without its own patch a Theme inherits the default look: faded, with a dashed contour around boxes and dashed lines. A patch in `edge` or `message` restyles lines',
  hover: 'The Dev UI: the element under the pointer',
  selected: 'The Dev UI: the selected element',
  ghost: 'The Dev UI: the Node being dragged',
  'on-path': 'The Dev UI: the Nodes and Edges of the highlighted path',
  dimmed: 'The Dev UI: what is off the highlighted path',
  focus: 'The Dev UI: the element with keyboard focus',
};

const FAMILIES: Readonly<Record<string, string>> = {
  forma: 'shape',
  relleno: 'fill',
  borde: 'border',
  sombra: 'shadow',
  glow: 'glow',
  vidrio: 'glass',
  filtro: 'filter',
  decoracion: 'decoration',
  trazo: 'stroke',
  marcador: 'marker',
  texto: 'text',
  codigo: 'code',
};

const PLACEMENTS: Readonly<Record<string, string>> = {
  'capa-nodo': 'node layer',
  'capa-pagina': 'page layer',
  'capa-arista': 'edge layer',
  marcador: 'marker',
};

const table = (header: readonly string[], rows: readonly (readonly string[])[]): string[] => [
  `| ${header.join(' | ')} |`,
  `| ${header.map(() => '---').join(' | ')} |`,
  ...rows.map((row) => `| ${row.join(' | ')} |`),
];

export function catalogReference(): string {
  const entries = Object.entries(CATALOG) as [string, PrimitiveDefinition][];
  const families = [...new Set(entries.map(([, definition]) => definition.familia))];
  const lines: string[] = [
    '# Theme catalog reference',
    '',
    'Generated by `pnpm docs:catalog` from the catalog of `packages/theme`; do not edit by hand. The contract is in `docs/adr/0008-expressive-theme-system.md`.',
    '',
    'A number is written as `min to max (default)`; out of range is an error, never clamped. Colors are always Palette names. "Metrics" says whether the Primitive can change the box or the Slots (by default it only paints).',
    '',
    '## Primitives',
  ];
  lines.push(
    '',
    'Every Node or Group Layer (except `code`) also accepts, without the Primitive declaring them: `offset x y` (written with two values and stored as `offset-x`/`offset-y`; negatives allowed) and `grow`. They only paint: they do not change the Metrics or cause a relayout, and a state patch can change them with `transition`.',
    '',
    ...table(['Common property', 'Range'], Object.entries(OFFSET_PROPERTIES).map(([key, value]) => [`\`${key}\``, `${value.min} to ${value.max}`])),
    '',
    `And \`zone\` (${ZONE_PROPERTY.zone.valores.map((v) => `\`${v}\``).join(', ')}; without it, \`all\`): which part of the box the Layer paints. \`header\` is the zone of the Slots before \`attrs\` (without \`attrs\` it equals \`all\`) and \`body\` that of \`attrs\`. It only paints, and is applied apart from the box: a state patch does not change it.`,
  );
  for (const family of families) {
    lines.push('', `### ${(FAMILIES[family] ?? family).replace(/^./, (c) => c.toUpperCase())} family`, '');
    const rows = entries
      .filter(([, definition]) => definition.familia === family)
      .map(([name, definition]) => {
        const props = Object.entries(definition.propiedades).map(([key, value]) => property(key, value));
        if (definition.abierta === true) props.push('free parameters (number or text)');
        return [`\`${name}\``, placementsOf(name as PrimitiveName).map((u) => PLACEMENTS[u] ?? u).join(', '), props.join('; ') || '-', definition.afectaMetricas ? 'yes' : 'no'];
      });
    lines.push(...table(['Primitive', 'Placement', 'Properties', 'Metrics'], rows));
  }
  lines.push('', '## Slots', '', ...table(['Slot', 'Style'], SLOTS.map((slot) => [`\`${slot}\``, `\`${SLOT_DEFINITION[slot].estilo}\``])));
  lines.push(
    '',
    '## States',
    '',
    'A `state <name> { ... }` patch only paints: it never changes the Metrics. Later rows win over earlier ones when an element is in several states.',
    '',
    ...table(['State', 'Set by'], STATES.map((state) => [`\`${state}\``, STATE_ORIGIN[state]])),
    '',
    '## ER table row (`row`)',
    '',
    `Theme block that styles the rows of an \`er\` View. \`height\` (${ROW_HEIGHT.min} to ${ROW_HEIGHT.max}) and the \`size\` of \`name\`, \`type\` and \`key\` (a multiple of the Theme text size, as in the Slots) change the measured size; the rest only paints.`,
    '',
    ...table(
      ['Element', 'Content'],
      [
        ['`layer`, `use`', 'Layer stack of each row (Node Primitives)'],
        ['`alternate { ... }`', 'Patch for odd rows'],
        [`\`key ${ROW_KEYS.join('|')} { ... }\``, 'Patch for rows with that key mark, in that order'],
        ['`optional { ... }`', 'Patch for optional Attributes, after the keys'],
        ['`state hover|selected|... { ... }`', 'Row state patch (only paints), over the stack of its variant; the shell emits `hover` and `selected`'],
        ...ROW_TEXT_NAMES.map((name) => [`\`${name} { ... }\``, `Text style with the \`${ROW_TEXTS[name]}\` Primitive${name === 'key' ? ' (the chip of each key mark)' : ''}`]),
      ],
    ),
    '',
    '## Sequence elements',
    '',
    'Theme blocks for a `sequence` View; without them the core derives them from `edge` and `node`. Each accepts `layer`, `use` and `state`; the Metrics are the sequence spacings (px, with their range and core default).',
    '',
    ...table(
      ['Block', 'Layers', 'Markers', 'Styles', 'Patches', 'Metrics'],
      SEQUENCE_BLOCKS.map((name) => {
        const e = SEQUENCE_SPEC[name];
        const metrics = Object.entries(e.metricas).map(([key, m]) => `\`${key}\` ${m.min} to ${m.max} (${m.defecto})`);
        return [
          `\`${name}\``,
          e.capas === 'capa-arista' ? 'strokes' : 'Node',
          e.marcadores.map((m) => `\`${m}\``).join(', ') || '-',
          Object.entries(e.textos).map(([key, t]) => `\`${key}\` (\`${t.primitiva}\`)`).join(', ') || '-',
          e.parches === undefined ? '-' : `\`${e.parches.palabra} <${e.parches.palabra === 'kind' ? 'kind' : 'operator'}>\`: ${e.parches.nombres.join(', ')}`,
          metrics.join('; ') || '-',
        ];
      }),
    ),
    '',
    'The `identifying { ... }` patch of the `edge` block changes the stroke of the identifying Edges of an ER View.',
    '',
    '## Motions',
    '',
    ...table(
      ['Motion', 'Intensity', 'Easing', 'Duration (ms)'],
      Object.entries(MOTIONS).map(([name, motion]) => [`\`${name}\``, motion.intensidad ? 'yes' : 'no', motion.easing, String(motion.duracionMs)]),
    ),
    '',
    `Easings: ${EASINGS.map((easing) => `\`${easing}\``).join(', ')}.`,
    '',
    '## Enter and exit effects',
    '',
    ...table(['Effect'], EFFECTS.map((effect) => [`\`${effect}\``])),
    '',
    '## Properties animatable with keyframes',
    '',
    ...table(
      ['Property', 'Range'],
      Object.entries(ANIMATABLE_PROPERTIES).map(([name, range]) => [`\`${name}\``, `${range.min} to ${range.max}`]),
    ),
    '',
  );
  return lines.join('\n');
}
