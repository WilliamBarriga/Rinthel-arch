/**
 * Keywords of the editor highlighting, extracted at build time from the `dsl` grammar (research `editor-dsl-ui`): so
 * the browser does not load Langium. `generateKeywords()` rewrites `browser/editor/keywords.ts` if it changed; a test
 * fails if the committed list drifts from the grammar.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const GRAMMAR = fileURLToPath(new URL('../../dsl/src/grammar/diagrams.langium', import.meta.url));
const TARGET = fileURLToPath(new URL('../browser/editor/keywords.ts', import.meta.url));

/** The word-shaped literals (`'view'`, `'ease-in-out'`), without repeats and in alphabetical order. */
export function grammarKeywords(grammar: string): string[] {
  const words = new Set<string>();
  for (const [, word] of grammar.matchAll(/'([a-z][a-z-]*)'/g)) words.add(word as string);
  return [...words].sort();
}

export function keywordsModule(words: readonly string[]): string {
  const lines = words.map((p) => `  '${p}',`).join('\n');
  return `/** Generated by \`scripts/keywords.ts\` in the \`dev-ui\` build from the \`dsl\` grammar; do not edit by hand. */\nexport const KEYWORDS: readonly string[] = [\n${lines}\n];\n`;
}

export function generateKeywords(): void {
  const module = keywordsModule(grammarKeywords(readFileSync(GRAMMAR, 'utf8')));
  let current: string | undefined;
  try {
    current = readFileSync(TARGET, 'utf8');
  } catch {
    current = undefined;
  }
  if (current !== module) writeFileSync(TARGET, module);
}
