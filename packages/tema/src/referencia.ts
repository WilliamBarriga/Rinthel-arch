/** Catalog reference in Markdown (English), generated from the same tables that validate. */
import { EASINGS, EFECTOS, MOVIMIENTOS, PROPIEDADES_ANIMABLES } from './animacion';
import { BLOQUES_DE_SECUENCIA, ESPECIFICACION_DE_SECUENCIA } from './secuencia';
import { ALTO_DE_FILA, CLAVES_DE_FILA, NOMBRES_DE_TEXTO_DE_FILA, TEXTOS_DE_FILA } from './fila';
import { ESTADOS } from './parches';
import type { Estado } from './parches';
import { CATALOGO, DEFINICION_DE_SLOT, PROPIEDADES_DE_DESPLAZAMIENTO, PROPIEDAD_DE_ZONA, SLOTS, ubicacionesDe } from './catalogo';
import type { DefinicionDePrimitiva, DefinicionDePropiedad, NombreDePrimitiva } from './catalogo';

const propiedad = (nombre: string, definicion: DefinicionDePropiedad): string => {
  switch (definicion.tipo) {
    case 'numero':
      return `\`${nombre}\` ${definicion.min} to ${definicion.max}${definicion.defecto !== undefined ? ` (${definicion.defecto})` : definicion.opcional === true ? ' (optional)' : ''}`;
    case 'color':
      return `\`${nombre}\` Palette color${definicion.opcional === true ? ' (optional)' : ''}`;
    case 'opcion':
      return `\`${nombre}\` ${definicion.valores.join('|')}${definicion.defecto !== undefined ? ` (${definicion.defecto})` : definicion.opcional === true ? ' (optional)' : ''}`;
    case 'nombre':
      return `\`${nombre}\` Component name`;
    case 'texto':
      return `\`${nombre}\` text up to ${definicion.largo} characters${definicion.opcional === true ? ' (optional)' : ''}`;
  }
};

/** Quien pone cada estado; la tabla obliga a describir un estado nuevo. */
const ORIGEN_DE_ESTADO: Readonly<Record<Estado, string>> = {
  planned: 'The Model: Planned elements. Without its own patch a Theme inherits the default look: faded, with a dashed contour around boxes and dashed lines. A patch in `edge` or `message` restyles lines',
  hover: 'The Dev UI: the element under the pointer',
  selected: 'The Dev UI: the selected element',
  ghost: 'The Dev UI: the Node being dragged',
  'on-path': 'The Dev UI: the Nodes and Edges of the highlighted path',
  dimmed: 'The Dev UI: what is off the highlighted path',
  focus: 'The Dev UI: the element with keyboard focus',
};

const FAMILIAS: Readonly<Record<string, string>> = {
  forma: 'shape',
  relleno: 'fill',
  borde: 'border',
  sombra: 'shadow',
  glow: 'glow',
  vidrio: 'glass',
  filtro: 'filter',
  decoracion: 'decoration',
  trazo: 'stroke',
  marcador: 'marker',
  texto: 'text',
  codigo: 'code',
};

const UBICACIONES: Readonly<Record<string, string>> = {
  'capa-nodo': 'node layer',
  'capa-pagina': 'page layer',
  'capa-arista': 'edge layer',
  marcador: 'marker',
};

const tabla = (cabecera: readonly string[], filas: readonly (readonly string[])[]): string[] => [
  `| ${cabecera.join(' | ')} |`,
  `| ${cabecera.map(() => '---').join(' | ')} |`,
  ...filas.map((fila) => `| ${fila.join(' | ')} |`),
];

export function referenciaDelCatalogo(): string {
  const entradas = Object.entries(CATALOGO) as [string, DefinicionDePrimitiva][];
  const familias = [...new Set(entradas.map(([, definicion]) => definicion.familia))];
  const lineas: string[] = [
    '# Theme catalog reference',
    '',
    'Generated by `pnpm docs:catalogo` from the catalog of `packages/tema`; do not edit by hand. The contract is in `docs/adr/0008-expressive-theme-system.md`.',
    '',
    'A number is written as `min to max (default)`; out of range is an error, never clamped. Colors are always Palette names. "Metrics" says whether the Primitive can change the box or the Slots (by default it only paints).',
    '',
    '## Primitives',
  ];
  lineas.push(
    '',
    'Every Node or Group Layer (except `code`) also accepts, without the Primitive declaring them: `offset x y` (written with two values and stored as `offset-x`/`offset-y`; negatives allowed) and `grow`. They only paint: they do not change the Metrics or cause a relayout, and a state patch can change them with `transition`.',
    '',
    ...tabla(['Common property', 'Range'], Object.entries(PROPIEDADES_DE_DESPLAZAMIENTO).map(([clave, valor]) => [`\`${clave}\``, `${valor.min} to ${valor.max}`])),
    '',
    `And \`zone\` (${PROPIEDAD_DE_ZONA.zone.valores.map((v) => `\`${v}\``).join(', ')}; without it, \`all\`): which part of the box the Layer paints. \`header\` is the zone of the Slots before \`attrs\` (without \`attrs\` it equals \`all\`) and \`body\` that of \`attrs\`. It only paints, and is applied apart from the box: a state patch does not change it.`,
  );
  for (const familia of familias) {
    lineas.push('', `### ${(FAMILIAS[familia] ?? familia).replace(/^./, (c) => c.toUpperCase())} family`, '');
    const filas = entradas
      .filter(([, definicion]) => definicion.familia === familia)
      .map(([nombre, definicion]) => {
        const props = Object.entries(definicion.propiedades).map(([clave, valor]) => propiedad(clave, valor));
        if (definicion.abierta === true) props.push('free parameters (number or text)');
        return [`\`${nombre}\``, ubicacionesDe(nombre as NombreDePrimitiva).map((u) => UBICACIONES[u] ?? u).join(', '), props.join('; ') || '-', definicion.afectaMetricas ? 'yes' : 'no'];
      });
    lineas.push(...tabla(['Primitive', 'Placement', 'Properties', 'Metrics'], filas));
  }
  lineas.push('', '## Slots', '', ...tabla(['Slot', 'Style'], SLOTS.map((slot) => [`\`${slot}\``, `\`${DEFINICION_DE_SLOT[slot].estilo}\``])));
  lineas.push(
    '',
    '## States',
    '',
    'A `state <name> { ... }` patch only paints: it never changes the Metrics. Later rows win over earlier ones when an element is in several states.',
    '',
    ...tabla(['State', 'Set by'], ESTADOS.map((estado) => [`\`${estado}\``, ORIGEN_DE_ESTADO[estado]])),
    '',
    '## ER table row (`row`)',
    '',
    `Theme block that styles the rows of an \`er\` View. \`height\` (${ALTO_DE_FILA.min} to ${ALTO_DE_FILA.max}) and the \`size\` of \`name\`, \`type\` and \`key\` (a multiple of the Theme text size, as in the Slots) change the measured size; the rest only paints.`,
    '',
    ...tabla(
      ['Element', 'Content'],
      [
        ['`layer`, `use`', 'Layer stack of each row (Node Primitives)'],
        ['`alternate { ... }`', 'Patch for odd rows'],
        [`\`key ${CLAVES_DE_FILA.join('|')} { ... }\``, 'Patch for rows with that key mark, in that order'],
        ['`optional { ... }`', 'Patch for optional Attributes, after the keys'],
        ['`state hover|selected|... { ... }`', 'Row state patch (only paints), over the stack of its variant; the shell emits `hover` and `selected`'],
        ...NOMBRES_DE_TEXTO_DE_FILA.map((nombre) => [`\`${nombre} { ... }\``, `Text style with the \`${TEXTOS_DE_FILA[nombre]}\` Primitive${nombre === 'key' ? ' (the chip of each key mark)' : ''}`]),
      ],
    ),
    '',
    '## Sequence elements',
    '',
    'Theme blocks for a `sequence` View; without them the core derives them from `edge` and `node`. Each accepts `layer`, `use` and `state`; the Metrics are the sequence spacings (px, with their range and core default).',
    '',
    ...tabla(
      ['Block', 'Layers', 'Markers', 'Styles', 'Patches', 'Metrics'],
      BLOQUES_DE_SECUENCIA.map((nombre) => {
        const e = ESPECIFICACION_DE_SECUENCIA[nombre];
        const metricas = Object.entries(e.metricas).map(([clave, m]) => `\`${clave}\` ${m.min} to ${m.max} (${m.defecto})`);
        return [
          `\`${nombre}\``,
          e.capas === 'capa-arista' ? 'strokes' : 'Node',
          e.marcadores.map((m) => `\`${m}\``).join(', ') || '-',
          Object.entries(e.textos).map(([clave, t]) => `\`${clave}\` (\`${t.primitiva}\`)`).join(', ') || '-',
          e.parches === undefined ? '-' : `\`${e.parches.palabra} <${e.parches.palabra === 'kind' ? 'kind' : 'operator'}>\`: ${e.parches.nombres.join(', ')}`,
          metricas.join('; ') || '-',
        ];
      }),
    ),
    '',
    'The `identifying { ... }` patch of the `edge` block changes the stroke of the identifying Edges of an ER View.',
    '',
    '## Motions',
    '',
    ...tabla(
      ['Motion', 'Intensity', 'Easing', 'Duration (ms)'],
      Object.entries(MOVIMIENTOS).map(([nombre, movimiento]) => [`\`${nombre}\``, movimiento.intensidad ? 'yes' : 'no', movimiento.easing, String(movimiento.duracionMs)]),
    ),
    '',
    `Easings: ${EASINGS.map((easing) => `\`${easing}\``).join(', ')}.`,
    '',
    '## Enter and exit effects',
    '',
    ...tabla(['Effect'], EFECTOS.map((efecto) => [`\`${efecto}\``])),
    '',
    '## Properties animatable with keyframes',
    '',
    ...tabla(
      ['Property', 'Range'],
      Object.entries(PROPIEDADES_ANIMABLES).map(([nombre, rango]) => [`\`${nombre}\``, `${rango.min} to ${rango.max}`]),
    ),
    '',
  );
  return lineas.join('\n');
}
